@torch.no_grad()
def draft_early(ci, g, sig, prev, k_rej, signal, tau, cpath, probe_nodes, tm, rec):
    """4-node draft of chunk ci with an early check after node k_rej: the TARGET predicts x0 from the draft's intermediate z (one forward, same KV context);
    signal: diff = ||x0_T - x0_D||^2 / numel (the score difference), crit = drift critic on x0_T, critD = drift critic on x0_D. Reject (return None) if score > tau
    → the remaining draft nodes are skipped. probe_nodes: also log every signal at those nodes (no rejection) + the final node's signals."""
    z = D.chunk_noise(ci, g); x0 = None; steps = 0; sc = None
    for i in range(len(sig)):
        t1 = time.time(); x0 = D.target_x0(z, i, ci); tm["draft"] += time.time() - t1; steps += 1
        if (i in probe_nodes) or i == k_rej:
            t1 = time.time(); xT = Tg.target_x0(z, i, ci); d = float(((xT - x0) ** 2).mean()); lT = critic_logit(xT, prev, ci, cpath) if cpath else None; lD = critic_logit(x0, prev, ci, cpath) if cpath else None; tm["verify"] += time.time() - t1
            rec.setdefault("nodes", {})[str(i)] = dict(sigma=round(sig[i], 3), diff=round(d, 5), critT=None if lT is None else round(lT, 3), critD=None if lD is None else round(lD, 3))
            if i == k_rej:
                sc = d if signal == "diff" else (lT if signal == "crit" else lD)
                if sc is not None and sc > tau: rec["steps"] = steps; rec["rejected_at"] = i; return None, sc, steps
        if i < len(sig) - 1: s_ = sig[i + 1]; z = (1 - s_) * x0 + s_ * D.randn_like(x0, g)
    rec["steps"] = steps; rec["final_critD"] = round(critic_logit(x0.float(), prev, ci, cpath), 3) if cpath else None
    return x0.float(), sc, steps
