@torch.no_grad()
def agree_chunk(ci, g, sig, K, tau, mode, tm, rec):
    """target-agreement verifier. Draft runs nodes 0..K; the TARGET predicts x0 from the same z_K (at K = 0 this is the target's own first step: same noise).
    d = ||x0_T - x0_D||^2 / ||x0_T||^2 (mode contains 'lf': on 4x4 spatially pooled latents = layout/colour only).
    accept (d <= tau): draft finishes nodes K+1.. from its own x0 (mode 'h': from the TARGET's x0 = target layout, draft detail);
    reject: target finishes from its own x0 at node K -> for K = 0 the chunk equals the target-only chunk (same noise draws)."""
    z = D.chunk_noise(ci, g)
    for i in range(K + 1):
        t1 = time.time(); xd = D.target_x0(z, i, ci); tm["draft"] += time.time() - t1
        if i < K: s_ = sig[i + 1]; z = (1 - s_) * xd + s_ * D.randn_like(xd, g)
    t1 = time.time(); xt = Tg.target_x0(z, K, ci); tm["verify"] += time.time() - t1
    rel = lambda A, B_: float(((A - B_) ** 2).mean() / (A ** 2).mean().clamp_min(1e-8)); d_full = rel(xt.float(), xd.float()); d_lf = rel(_lp(xt), _lp(xd)); d = d_lf if "lf" in mode else d_full
    acc = d <= tau; stK = g.get_state()
    def finish(Bd, x, start):
        for i in range(start + 1, len(sig)):
            s_ = sig[i]; zz = (1 - s_) * x + s_ * Bd.randn_like(x, g); x = Bd.target_x0(zz, i, ci)
        return x.float()
    t1 = time.time(); out = finish(D, xt if "h" in mode else xd, K) if acc else finish(Tg, xt, K); tm["draft" if acc else "target"] += time.time() - t1
    rec.update(d=round(d, 5), d_full=round(d_full, 5), d_lf=round(d_lf, 5), acc=bool(acc))
    if a.agree_shadow:
        st_end = g.get_state(); g.set_state(stK); other = finish(Tg, xt, K) if acc else finish(D, xt if "h" in mode else xd, K); g.set_state(st_end)
        xT_full = other if acc else out; xD_full = out if acc else other; rec["local_err"] = round(float(((xD_full - xT_full) ** 2).mean() / (xT_full ** 2).mean()), 5)
    return out, acc, d
