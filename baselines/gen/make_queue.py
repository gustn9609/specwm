#!/usr/bin/env python3
"""[10/17 frozen baselines] Build the tier-1 BASELINE generation queue (CPU only): job lists per baseline from the frozen scene subsets
(gen/frozen_scenes.py: scenes/<set>/FROZEN.json when present, else the COMMON fallback rule) x the 7 control programs, split into chunks sized for
<= 20-min GPU-lock holds, one shell script per chunk under gen/queue/1/<NNN>_<baseline>_p<NN>.sh.  Each chunk script takes the GPU index as $1 and runs
the baseline's own batch command under  flock /tmp/gpu$1.lock env CUDA_VISIBLE_DEVICES=$1  (one hold per chunk, hold time + peak GPU memory logged by
baselines/_gpu_peak_run.sh); it is idempotent (done clips = video.mp4 + timing.json are filtered out by gen/filter_pending.py and skipped by every
runner as well) and exits non-zero when any clip failed.  Queue order: waypoint, mg2, abot, astra, abot_t5offload, astra_nocap (last).
  baseline        runs dir / clip names                                      jobs                                   clips/part  batch command
  waypoint        runs/waypoint/{wp|neutral_wp}__<scene>__<P>                TSV  IMAGE  P  1234  NAME               20          waypoint/run.sh --batch LIST.tsv OUTROOT (WP_JOBS per part)
  mg2             runs/mg2/{mg2|neutral_mg2}__<scene>__<P>                   JSON {image, program, seed, out}        60          mg2/run.sh --batch JOBS.json
  abot            runs/abot/{abot|neutral_abot}__<scene>__<P>                abot/make_jobs.py (neutral: --no-caption)  12       abot/run.sh --batch JOBS.json
  astra           runs/astra/{astra|neutral_832}__<scene>__<P>               astra/make_jobs.py (neutral: --prefix neutral_832)  5   astra/run.sh batch JOBS.json
  abot_t5offload  runs/abot_t5offload/abot__<scene>__<P>  (3 scenes x P1-P5)  abot/make_jobs.py                      12          abot/run.sh --batch JOBS.json --offload-t5 on
  astra_nocap     runs/astra_nocap/neutral_832__<scene>__<P>_nocap            astra/make_jobs.py --no-caption --suffix _nocap  5  astra/run.sh batch JOBS.json
Baseline clips carry the OURS set prefix (wp, neutral_wp, mg2, neutral_mg2, abot, neutral_abot, astra, neutral_832 [+ _nocap]) so baselines/report.py pairs
them with runs/ours_teacher_<set><suffix>/<same clip name>.  Outputs: gen/jobs/<baseline>[_pNN].{tsv,json}, gen/queue/1/*.sh, gen/queue/INDEX.tsv.
usage: python3 /home/hk28965/specwm/baselines/gen/make_queue.py [--programs P1,P2,P2p,P3,P4,P4p,P5] [--seed 1234] [--tier 1]   (plain python3; re-run any time)"""
import os, sys, json, glob, argparse, subprocess, time
B = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); GEN = B + "/gen"; sys.path.insert(0, GEN)
import frozen_scenes as FS
ap = argparse.ArgumentParser(); ap.add_argument("--programs", default="P1,P2,P2p,P3,P4,P4p,P5"); ap.add_argument("--seed", type=int, default=1234); ap.add_argument("--tier", default="1")
a = ap.parse_args(); P = [p for p in a.programs.split(",") if p]; SEED = a.seed
SIZES = dict(waypoint=20, mg2=60, abot=12, astra=4, abot_t5offload=12, astra_nocap=4)                 # clips per chunk (<= 20-min holds, orchestrator numbers)
T5OFF_PREF = ["desert_valley_3rd", "ruins_explorer_3rd", "suburban_house_1st"]   # abot_t5offload subset: the HF-Space 3rd-person example (its smoke clip exists), ABot's official bench image, the captioned 1st-person preset
JOBS = GEN + "/jobs"; QUEUE = "%s/queue/%s" % (GEN, a.tier); os.makedirs(JOBS, exist_ok=True); os.makedirs(QUEUE, exist_ok=True); os.makedirs(GEN + "/logs", exist_ok=True)
MARK = "# generated by gen/make_queue.py"
SC, SRC = {}, {}
for s in ("wp", "mg2", "abot", "astra", "neutral"): SC[s] = FS.frozen(s); SRC[s] = FS.frozen.source
print("[make_queue] frozen scenes: " + "; ".join("%s %d (%s)" % (s, len(SC[s]), "FROZEN.json" if SRC[s].endswith("FROZEN.json") else "fallback") for s in SC))


def run_maker(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: sys.exit("[make_queue] job maker failed: %s\n%s%s" % (" ".join(cmd), r.stdout[-1500:], r.stderr[-1500:]))
    print("[make_queue] " + (r.stdout.strip().splitlines() or ["(no output)"])[-1])


def chunks(seq, n): return [seq[i:i + n] for i in range(0, len(seq), n)]


def sets_of(items, key):
    c = {}
    for it in items: k = key(it); c[k] = c.get(k, 0) + 1
    return " + ".join("%s %d" % kv for kv in sorted(c.items()))


# ------------------------------------------------------------------ job lists
# 1. Waypoint: TSV lines IMAGE  P  SEED  NAME (tab-separated), sets wp (own scenes) and neutral_wp (neutral scenes, text-free model: no caption anyway)
wp_rows = [(FS.image_path("wp", s), p, SEED, "wp__%s__%s" % (s, p)) for s in SC["wp"] for p in P] + \
          [(FS.image_path("neutral", s), p, SEED, "neutral_wp__%s__%s" % (s, p)) for s in SC["neutral"] for p in P]
with open(JOBS + "/waypoint.tsv", "w") as f:
    f.write("# Waypoint-1.5 frozen queue (%s): IMAGE\tPROGRAM\tSEED\tNAME -> runs/waypoint/NAME; %d clips\n" % (time.strftime("%Y-%m-%d %H:%M"), len(wp_rows)))
    for r in wp_rows: f.write("%s\t%s\t%d\t%s\n" % r)
# 2. Matrix-Game 2.0: JSON jobs for run_mg2.py --jobs (image, program, seed, out); text-free model
mg2_jobs = [dict(image=FS.image_path("mg2", s), program=p, seed=SEED, out="%s/runs/mg2/mg2__%s__%s" % (B, s, p), set="mg2", scene=s) for s in SC["mg2"] for p in P] + \
           [dict(image=FS.image_path("neutral", s), program=p, seed=SEED, out="%s/runs/mg2/neutral_mg2__%s__%s" % (B, s, p), set="neutral_mg2", scene=s) for s in SC["neutral"] for p in P]
json.dump(mg2_jobs, open(JOBS + "/mg2.json", "w"), indent=1)
# 3. ABot: abot/make_jobs.py (own scenes with their captions; neutral scenes --no-caption = text-free baseline arm)
run_maker(["python3", B + "/abot/make_jobs.py", JOBS + "/abot_own.json", "--out-root", B + "/runs/abot", "--set", "abot", "--scenes", ",".join(SC["abot"]), "--programs", ",".join(P), "--seed", str(SEED)])
run_maker(["python3", B + "/abot/make_jobs.py", JOBS + "/abot_neutral.json", "--out-root", B + "/runs/abot", "--set", "neutral_abot", "--scenes-dir", B + "/scenes/neutral", "--scenes", ",".join(SC["neutral"]), "--programs", ",".join(P), "--seed", str(SEED), "--no-caption"])
abot_jobs = json.load(open(JOBS + "/abot_own.json")) + json.load(open(JOBS + "/abot_neutral.json")); json.dump(abot_jobs, open(JOBS + "/abot.json", "w"), indent=1)
# 3b. ABot with the official T5 offload (19 GiB path): 15-clip subset = 3 scenes x P1-P5
t5_scenes = [s for s in T5OFF_PREF if s in SC["abot"]]
for s in SC["abot"]:
    if len(t5_scenes) >= 3: break
    if s not in t5_scenes: t5_scenes.append(s)
run_maker(["python3", B + "/abot/make_jobs.py", JOBS + "/abot_t5offload.json", "--out-root", B + "/runs/abot_t5offload", "--set", "abot", "--scenes", ",".join(t5_scenes), "--programs", "P1,P2,P3,P4,P5", "--seed", str(SEED)])
t5_jobs = json.load(open(JOBS + "/abot_t5offload.json"))
# 4. Astra: own scenes (captioned, 21) + neutral captioned (prefix neutral_832) ; 4b. neutral --no-caption (suffix _nocap, runs/astra_nocap)
run_maker(["python3", B + "/astra/make_jobs.py", "astra", "--scenes", ",".join(SC["astra"]), "--programs", ",".join(P), "--seed", str(SEED), "--out", JOBS + "/astra_own.json"])
run_maker(["python3", B + "/astra/make_jobs.py", "neutral", "--prefix", "neutral_832", "--scenes-dir", B + "/scenes/neutral", "--scenes", ",".join(SC["neutral"]), "--programs", ",".join(P), "--seed", str(SEED), "--out", JOBS + "/astra_neutral.json"])
astra_jobs = json.load(open(JOBS + "/astra_own.json")) + json.load(open(JOBS + "/astra_neutral.json")); json.dump(astra_jobs, open(JOBS + "/astra.json", "w"), indent=1)
run_maker(["python3", B + "/astra/make_jobs.py", "neutral", "--prefix", "neutral_832", "--scenes-dir", B + "/scenes/neutral", "--scenes", ",".join(SC["neutral"]), "--programs", ",".join(P), "--seed", str(SEED), "--no-caption", "--suffix", "_nocap", "--out", JOBS + "/astra_nocap.json"])
nocap_jobs = json.load(open(JOBS + "/astra_nocap.json"))
for j in astra_jobs + nocap_jobs + abot_jobs + t5_jobs: assert j["out"].startswith(B + "/runs/"), j["out"]

# ------------------------------------------------------------------ chunk scripts
TEMPLATE = """#!/bin/bash
{mark} {date} -- do not edit by hand (re-run make_queue.py)
# [10/17 frozen baselines] queue tier {tier} / {nnn}: {baseline} part {pp}/{np} -- {n} clips ({sets}) -> {runs}
# usage: {script} GPU_INDEX          (DRY=1 {script} G prints the batch command instead of running it)
# Holds flock /tmp/gpu<GPU>.lock for the whole batch (sized for <= 20 min). Idempotent: done clips (video.mp4 + timing.json) are filtered out first
# (gen/filter_pending.py -> {pend}) and skipped by the runner too; a failing clip is marked in its out dir and the batch goes on; exit != 0 if any
# clip failed (2 = filter error). Hold time + peak GPU memory during the hold (nvidia-smi, baselines/_gpu_peak_run.sh) go to {log}.
G=${{1:?usage: $0 GPU_INDEX}}; S=/home/hk28965/specwm; B=$S/baselines; J=$B/gen/jobs; L={log}; mkdir -p $B/gen/logs
SRC={src}; PEND={pend}
N=$(python3 $B/gen/filter_pending.py "$SRC" "$PEND"{filter_extra}) || {{ echo "[queue] filter_pending failed on $SRC" | tee -a $L; exit 2; }}
echo "[queue $(date '+%m/%d %H:%M:%S')] {nnn} {baseline} p{pp}: $N of {n} clips pending (gpu $G)" | tee -a $L
[ "$N" -gt 0 ] || exit 0
CMD=({cmd})
if [ "${{DRY:-0}}" = 1 ]; then echo "DRY: flock /tmp/gpu$G.lock env CUDA_VISIBLE_DEVICES=$G $B/_gpu_peak_run.sh $G PEAKFILE ${{CMD[*]}}"; exit 0; fi
set -o pipefail; PK=$(mktemp); t0=$(date +%s)
flock /tmp/gpu$G.lock env CUDA_VISIBLE_DEVICES=$G $B/_gpu_peak_run.sh $G "$PK" "${{CMD[@]}}" 2>&1 | tee -a $L; RC=${{PIPESTATUS[0]}}
read -r HELD PEAK < "$PK" 2>/dev/null; rm -f "$PK"; WALL=$(( $(date +%s) - t0 ))
echo "[queue $(date '+%m/%d %H:%M:%S')] {nnn} {baseline} p{pp}: rc $RC, wall $WALL s = lock wait $(( WALL - ${{HELD:-0}} )) s + hold ${{HELD:-?}} s on gpu $G, peak GPU memory during the hold ${{PEAK:-?}} MiB" | tee -a $L
exit $RC
"""
for old in glob.glob(QUEUE + "/*.sh"):                       # remove only scripts this maker wrote earlier
    try:
        if MARK in open(old).read(2000): os.remove(old)
    except Exception: pass
index = []; nnn = 0
def emit(baseline, parts, ext, runs, cmd_fn, filter_extra="", key=lambda it: it["set"]):
    global nnn
    for i, part in enumerate(parts):
        nnn += 1; pp = "%02d" % (i + 1); stem = "%s_p%s" % (baseline, pp); src = "$J/%s.%s" % (stem, ext); pend = "$J/%s.pending.%s" % (stem, ext)
        path = "%s/%03d_%s_p%s.sh" % (QUEUE, nnn, baseline, pp)
        if ext == "tsv":
            with open("%s/%s.%s" % (JOBS, stem, ext), "w") as f:
                f.write("# %s part %s: IMAGE\tPROGRAM\tSEED\tNAME -> %s/NAME\n" % (baseline, pp, runs))
                for r in part: f.write("%s\t%s\t%d\t%s\n" % r)
        else: json.dump(part, open("%s/%s.%s" % (JOBS, stem, ext), "w"), indent=1)
        sets = sets_of(part, key); log = "$B/gen/logs/%03d_%s_p%s.log" % (nnn, baseline, pp)
        open(path, "w").write(TEMPLATE.format(mark=MARK, date=time.strftime("%Y-%m-%d %H:%M"), tier=a.tier, nnn="%03d" % nnn, baseline=baseline, pp=pp, np=len(parts), n=len(part), sets=sets, runs=runs,
                                               script=path, src=src, pend=pend, filter_extra=filter_extra, cmd=cmd_fn(stem), log=log)); os.chmod(path, 0o755)
        index.append(("%03d" % nnn, baseline, pp, len(part), sets, "gen/jobs/%s.%s" % (stem, ext), os.path.relpath(path, B), os.path.relpath(runs.replace("$B", B), B)))
emit("waypoint", chunks(wp_rows, SIZES["waypoint"]), "tsv", "$B/runs/waypoint", lambda st: 'env WP_JOBS=$J/%s/batch_jobs.json $B/waypoint/run.sh --batch "$PEND" $B/runs/waypoint' % st,
     filter_extra=" --out-root $B/runs/waypoint", key=lambda r: r[3].split("__")[0])
emit("mg2", chunks(mg2_jobs, SIZES["mg2"]), "json", "$B/runs/mg2", lambda st: '$B/mg2/run.sh --batch "$PEND"')
emit("abot", chunks(abot_jobs, SIZES["abot"]), "json", "$B/runs/abot", lambda st: '$B/abot/run.sh --batch "$PEND"')
emit("astra", chunks(astra_jobs, SIZES["astra"]), "json", "$B/runs/astra", lambda st: '$B/astra/run.sh batch "$PEND"')
emit("abot_t5offload", chunks(t5_jobs, SIZES["abot_t5offload"]), "json", "$B/runs/abot_t5offload", lambda st: '$B/abot/run.sh --batch "$PEND" --offload-t5 on')
emit("astra_nocap", chunks(nocap_jobs, SIZES["astra_nocap"]), "json", "$B/runs/astra_nocap", lambda st: '$B/astra/run.sh batch "$PEND"')
with open(GEN + "/queue/INDEX.tsv", "w") as f:
    f.write("# tier-%s baseline queue, %s; run in NNN order: bash <script> <GPU>; programs %s; seed %d; frozen scenes: %s\n" % (a.tier, time.strftime("%Y-%m-%d %H:%M"), ",".join(P), SEED,
            "; ".join("%s=%s" % (s, ",".join(SC[s])) for s in SC)))
    f.write("NNN\tbaseline\tpart\tclips\tsets\tjobs\tscript\truns_dir\n")
    for row in index: f.write("\t".join(str(x) for x in row) + "\n")
tot = {}
for row in index: tot[row[1]] = tot.get(row[1], 0) + row[3]
print("[make_queue] %d chunk scripts in %s (%s); %d clips: %s" % (len(index), QUEUE, GEN + "/queue/INDEX.tsv", sum(tot.values()), ", ".join("%s %d" % kv for kv in tot.items())))
print("[make_queue] abot_t5offload scenes: %s" % ", ".join(t5_scenes))
