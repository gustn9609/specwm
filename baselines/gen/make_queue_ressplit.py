#!/usr/bin/env python3
"""[10/20] Chunk maker for the resolution-split collaboration baseline arms rs576 / rs576r (gen/run_ressplit.sh; PROTOCOL rule-4 sets at 832x480 only:
neutral_832, astra [+ neutral_832_nocap on request]).  Writes self-contained .sh chunk scripts in the style of gen/queue/8/301_sf1p3b_nocap_idle.sh
(the chunk takes flock /tmp/gpu<G>.lock itself, runs _gpu_peak_run.sh + run_ressplit.sh SET ARM G CHUNKJSON, logs the hold / peak) into a PARK dir
(default gen/queue/park/ressplit/), NOT into the live queue: to enqueue, move the files you want into a live tier dir, e.g.
    mv /home/hk28965/specwm/baselines/gen/queue/park/ressplit/36?_*.sh /home/hk28965/specwm/baselines/gen/queue/9/
(worker.sh runs .sh chunks as `bash FILE G` without a lock, in name order inside a tier; the NNN prefix must not collide with names already in
that tier / claimed / done / failed -- re-run with --start N to renumber).  Each chunk embeds its chunk json ({"set","arm","tier","res","area","n",
"ids","made","tasks"}) as a heredoc written to raw/ours_<arm>_<set>/chunkdef_<name>.json; run_ressplit.sh skips tasks already frozen in
runs/ours_<arm>_<set>, so a chunk is idempotent.  Tasks already frozen are left out at make time too; the task order is the tasks json order
(FROZEN scene order x programs P1 P2 P2p P3 P4 P4p P5).
Chunk size: 12 clips (default; --size): 10/20 smoke on GPU 5 = load + warm-up ~ 4-6 min, then ~0.5-1 min per clip -> ~15-20 min hold.
usage: python3 /home/hk28965/specwm/baselines/gen/make_queue_ressplit.py [--sets neutral_832,astra] [--arms rs576,rs576r] [--size 12] [--start 360]
       [--out-dir gen/queue/park/ressplit] [--tier 9] [--gpus 0,1,2,3,4,5] [--dry-run]"""
import os, sys, json, time, argparse
B = "/home/hk28965/specwm/baselines"
def script(name, d, tier, gpus):
    stem = name[:-3]; js = json.dumps(d, indent=1); assert "\nEOF_CHUNK\n" not in js; gl = "|".join(gpus)
    return """#!/bin/bash
# generated by gen/make_queue_ressplit.py %(made)s -- tier %(tier)s: resolution-split collaboration baseline arm %(arm)s on %(set)s, %(n)d clips of 10 s at %(res)s
#   (cloud 14B FP8 2-step at 576x320 + device upsample%(ref)s, serial on ONE GPU; gen/run_ressplit.sh; re-run make_queue_ressplit.py, do not edit)
# RS_CHUNK set=%(set)s arm=%(arm)s n=%(n)d ids=%(ids)s
# usage: bash THIS GPU   (worker.sh runs .sh chunks so, WITHOUT a lock; this script takes flock /tmp/gpu$G.lock itself, GPUs %(gl)s only)
#   = flock /tmp/gpu$G.lock env CUDA_VISIBLE_DEVICES=$G _gpu_peak_run.sh G PEAK gen/run_ressplit.sh %(set)s %(arm)s G CHUNKJSON
#   Idempotent: tasks frozen in runs/ours_%(arm)s_%(set)s are skipped (nothing to do -> exit 0). Hold time + nvidia-smi peak logged below and in gen/logs/<NAME>.log.
G=${1:?usage: $0 GPU}; B=/home/hk28965/specwm/baselines; NAME=%(stem)s; L=$B/gen/logs/$NAME.log; mkdir -p $B/gen/logs
case "$G" in %(gl)s) ;; *) echo "[queue] $NAME: GPU $G not allowed (GPUs %(gl)s; 10/19: GPUs 6-7 are not ours)"; exit 1;; esac
CJ=$B/raw/ours_%(arm)s_%(set)s/chunkdef_$NAME.json; mkdir -p $B/raw/ours_%(arm)s_%(set)s
cat > $CJ.tmp <<'EOF_CHUNK'
%(js)s
EOF_CHUNK
mv -f $CJ.tmp $CJ
N=$(python3 -I -c "import json,sys,os; d=json.load(open(sys.argv[1])); print(sum(1 for t in d['tasks'] if not os.path.exists('%%s/runs/ours_%%s_%%s/%%s/timing.json' %% (sys.argv[2], d['arm'], d['set'], t['id']))))" $CJ $B)
echo "[queue $(date '+%%m/%%d %%H:%%M:%%S')] $NAME: $N of %(n)d clips pending (gpu $G), waiting for /tmp/gpu$G.lock" | tee -a $L
[ "$N" -gt 0 ] || exit 0
t0=$(date +%%s); PK=$(mktemp)
flock /tmp/gpu$G.lock env CUDA_VISIBLE_DEVICES=$G $B/_gpu_peak_run.sh $G "$PK" $B/gen/run_ressplit.sh %(set)s %(arm)s $G $CJ; rc=$?
read -r HELD PEAK < "$PK" 2>/dev/null; rm -f "$PK"
echo "[queue $(date '+%%m/%%d %%H:%%M:%%S')] $NAME: rc $rc, wall $(( $(date +%%s) - t0 )) s, lock hold ${HELD:-?} s, peak GPU memory ${PEAK:-?} MiB -> $B/runs/ours_%(arm)s_%(set)s" | tee -a $L
exit $rc
""" % dict(made=d["made"], tier=tier, set=d["set"], arm=d["arm"], n=d["n"], res=d["res"], ids=",".join(d["ids"]), stem=stem, js=js, gl=gl, ref=(" + 1.3B refiner LoRA" if d["arm"] == "rs576r" else " (bilinear, no refiner)"))
def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--sets", default="neutral_832,astra"); ap.add_argument("--arms", default="rs576,rs576r"); ap.add_argument("--size", type=int, default=12)
    ap.add_argument("--start", type=int, default=360, help="first NNN prefix"); ap.add_argument("--out-dir", default=B + "/gen/queue/park/ressplit"); ap.add_argument("--tier", default="9"); ap.add_argument("--gpus", default="0,1,2,3,4,5")
    ap.add_argument("--runs", default=B + "/runs"); ap.add_argument("--dry-run", action="store_true"); a = ap.parse_args()
    gpus = a.gpus.split(","); os.makedirs(a.out_dir, exist_ok=True); idx = a.start; made = []
    for tset in a.sets.split(","):
        p = "%s/tasks/%s.json" % (B, tset)
        if not os.path.exists(p): print("[skip] no tasks json", p); continue
        tasks = json.load(open(p)); res = {x["res"] for x in tasks}; area = {x["area"] for x in tasks}; assert len(res) == 1 and len(area) == 1, (tset, res, area); res = res.pop(); area = area.pop()
        if area != 399361: print("[skip] %s: area %d is not 832x480 (the rs arms refuse it)" % (tset, area)); continue
        for arm in a.arms.split(","):
            rd = "%s/ours_%s_%s" % (a.runs, arm, tset); todo = [x for x in tasks if not os.path.exists("%s/%s/timing.json" % (rd, x["id"]))]
            chunks = [todo[i:i + a.size] for i in range(0, len(todo), a.size)]
            print("[plan] %-12s %-7s %s: %3d tasks, %3d frozen, %3d to queue -> %d chunks of <= %d" % (tset, arm, res, len(tasks), len(tasks) - len(todo), len(todo), len(chunks), a.size))
            for ch in chunks:
                name = "%03d_%s_%s.sh" % (idx, tset, arm); idx += 1; f = os.path.join(a.out_dir, name)
                d = dict(set=tset, arm=arm, tier=a.tier, res=res, area=area, n=len(ch), ids=[x["id"] for x in ch], made=time.strftime("%Y-%m-%d %H:%M:%S"), tasks=ch)
                if not a.dry_run: open(f + ".tmp", "w").write(script(name, d, a.tier, gpus)); os.chmod(f + ".tmp", 0o755); os.replace(f + ".tmp", f)
                made.append(f)
    print("[park] %d chunk scripts%s -> %s" % (len(made), " (DRY RUN)" if a.dry_run else "", a.out_dir))
    for f in made: print("  ", os.path.basename(f))
    return 0
if __name__ == "__main__": sys.exit(main())
