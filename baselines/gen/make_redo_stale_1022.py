#!/usr/bin/env python3
"""[10/22] Re-run chunks for hybrid 60-s clips whose cloud corrections aged out unapplied (GPU shared with another user's training -> cloud refine 1.6 s >
device chunk 1.1 s -> lag 10-17 s -> 0 applied; the clip degenerated to device-only). Selection: runs/ours_*hyb*_dev_*/<clip>/timing.json with
chunks_sent > 0 and corrections_applied < 50 % of chunks_sent, modified after --since. Writes tier-11 pair chunks (FORCE=1 so run_ours.sh re-runs the frozen
ids; the chunk waits until NO other user's process is on either GPU of the pair, else defers itself) into --out (default gen/queue/redo_pending; move to
gen/queue/11 to launch). usage: make_redo_stale_1022.py [--since '2026-10-21 18:00'] [--out DIR] [--per 3]"""
import json, glob, os, time, argparse, collections, re
B = "/home/hk28965/specwm/baselines"
ap = argparse.ArgumentParser(); ap.add_argument("--since", default="2026-10-21 18:00"); ap.add_argument("--out", default=f"{B}/gen/queue/redo_pending"); ap.add_argument("--per", type=int, default=3); ap.add_argument("--start", type=int, default=500)
a = ap.parse_args(); t0 = time.mktime(time.strptime(a.since, "%Y-%m-%d %H:%M")); os.makedirs(a.out, exist_ok=True)
bad = collections.defaultdict(list)
for f in sorted(glob.glob(f"{B}/runs/ours_*hyb*_dev_*/*/timing.json")):
    if os.path.getmtime(f) < t0: continue
    t = json.load(open(f)); s = t.get("chunks_sent") or 0; ap_ = t.get("corrections_applied") or 0
    if s > 0 and ap_ < 0.5 * s:
        m = re.match(r"ours_(.+?)_dev_(.+)$", f.split("/")[-3]); bad[(m.group(1), m.group(2))].append(f.split("/")[-2])
n = a.start; made = []; stamp = time.strftime("%Y-%m-%d %H:%M:%S")
for (arm, st), ids in sorted(bad.items()):
    defs = {}
    for cj in glob.glob(f"{B}/raw/ours_{arm}_{st}/*chunkdef_*.json"):
        d = json.load(open(cj)); d = d.get("tasks", []) if isinstance(d, dict) else d
        for t in d: defs[t["id"]] = t
    tasks = [defs[i] for i in ids if i in defs]; assert len(tasks) == len(ids), (arm, st, set(ids) - set(defs))
    gate = "rt2c1hyb32_" + st.replace("_long", "") if arm.startswith("rt2c1hyb32") else "rt2c1hyb24_" + st.replace("_long", "")
    for k in range(0, len(tasks), a.per):
        T = tasks[k:k + a.per]; name = f"{n}_{st}_{arm}_redo"; n += 1
        body = json.dumps(dict(set=st, arm=arm, tier=11, res=T[0]["res"], area=T[0]["area"], n=len(T), ids=[t["id"] for t in T], made=stamp, redo="stale-cloud re-run (FORCE=1)", tasks=T, gates=[gate]), indent=1)
        sh = f"""#!/bin/bash
# generated by gen/make_redo_stale_1022.py {stamp} -- tier 11: RE-RUN (FORCE=1) of {len(T)} hybrid {arm} {st} clips whose cloud corrections aged out unapplied (GPU shared with another user); pair chunk
# HYB_CHUNK set={st} arm={arm} n={len(T)} gates={gate} ids={",".join(t["id"] for t in T)}
# usage: bash THIS GPU   (worker.sh). Waits until NO other user's process is on either GPU of the pair (compute sharing slows the cloud and the corrections age out), else defers itself.
G=${{1:?usage: $0 GPU}}; B={B}; NAME={name}
case "$G" in 0|1|2|3) ;; *) echo "[queue] $NAME: GPU $G: hybrids run only on the pairs 0+1 and 2+3"; exit 1;; esac
PG=$((G ^ 1)); LO=$(( G < PG ? G : PG )); HI=$(( G < PG ? PG : G )); QR=$B/gen/queue; CLEAN_WAIT=${{CLEAN_WAIT:-1800}}
others() {{ nvidia-smi --query-compute-apps=gpu_uuid,pid --format=csv,noheader | while IFS=', ' read u p; do i=$(nvidia-smi -L | grep -n "$u" | cut -d: -f1); i=$((i-1)); [ "$i" = "$LO" ] || [ "$i" = "$HI" ] || continue; ps -o user= -p $p 2>/dev/null | grep -qv '^hk28965' && echo "$i:$p"; done; }}
t0=$(date +%s); while :; do o=$(others); [ -z "$o" ] && break; [ $(( $(date +%s) - t0 )) -ge $CLEAN_WAIT ] && {{ echo "[queue] $NAME: other users' processes on the pair ($o) for ${{CLEAN_WAIT}} s -> DEFER (re-queued as $QR/11/$NAME.sh)"; cp -- "$0" $QR/11/$NAME.sh.tmp && chmod +x $QR/11/$NAME.sh.tmp && mv -f $QR/11/$NAME.sh.tmp $QR/11/$NAME.sh; exit 0; }}; sleep 60; done
CJ=$B/raw/ours_{arm}_{st}/chunkdef_$NAME.json; mkdir -p $B/raw/ours_{arm}_{st}
cat > $CJ.tmp <<'EOF_CHUNK'
{body}
EOF_CHUNK
mv -f $CJ.tmp $CJ
t0=$(date +%s); echo "[queue $(date '+%m/%d %H:%M:%S')] $NAME: {len(T)} clips FORCE=1, waiting for /tmp/gpu$LO.lock then /tmp/gpu$HI.lock (claimed by gpu $G)"
flock /tmp/gpu$LO.lock flock /tmp/gpu$HI.lock env CUDA_VISIBLE_DEVICES=$LO,$HI FORCE=1 $B/run_ours.sh {st} {arm} $G $CJ; RC=$?
echo "[queue $(date '+%m/%d %H:%M:%S')] $NAME: rc $RC, wall $(( $(date +%s) - t0 )) s"
exit $RC
"""
        p = f"{a.out}/{name}.sh"; open(p, "w").write(sh); os.chmod(p, 0o755); made.append((name, len(T)))
print("affected clips:", sum(len(v) for v in bad.values()), "in", len(bad), "cells"); [print("  %s %s: %d" % (k[0], k[1], len(v))) for k, v in sorted(bad.items())]
print("wrote %d chunks -> %s" % (len(made), a.out)); [print("  ", m) for m in made]
